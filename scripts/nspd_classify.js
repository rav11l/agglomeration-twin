// Классификация объектов НСПД по виду разрешённого использования (участки) и назначению/наименованию (здания).
// Применялась в браузере к результатам обхода WMS GetFeatureInfo (слои 36048 — участки, 36049 — здания)
// по сетке вокруг четырёх станций второй линии: участки — шаг 60 м, здания — шаг 30 м, радиус 1 км.
// Сырые ответы НСПД в депозит не входят; входят агрегаты data/nspd_line2_cadastre_aggregates.csv.
const clsLand = u => { u = (u || '').toLowerCase();
  if (/дорог|улиц|общее польз|общего польз|благоустр|парк|сквер|набережн|природн|лес|рекреац|водн|водозаб|12\.0|озелен|особо охран/.test(u)) return 'exempt';
  if (/гараж|автостоян|паркинг|стоянк|хранени. автотранс|2\.7\.1/.test(u)) return 'garage';
  if (/индивидуальн|ижс|2\.1[^.]|2\.1$|блокир/.test(u)) return 'izhs';
  if (/многокварт|многоэтаж|среднеэтаж|жил(ой|ые|ая|ых) (дом|комплекс|застр)|жилые дома|2\.5|2\.6/.test(u)) return 'mkd';
  if (/школ|общеобразоват|дошкол|детск|сад|образован|здравоохр|больниц|поликлин|спорт|культ|социальн|3\.[1-9]|5\.1/.test(u)) return 'social';
  if (/торгов|офис|делов|коммерч|магазин|общепит|гостини|обслужив|предпринимат|4\.[0-9]|склад|производ|промышл|6\.|коммунал|административ/.test(u)) return 'comm';
  return 'other'; };
const clsBuilding = r => { const u = (r.u || '').toLowerCase(), n = (r.name || '').toLowerCase();
  if (/многокварт|^жилое|жилой дом/.test(u) && !/нежил/.test(u)) return 'mkd';
  if (/гараж|стоянк|паркинг|автостоян|машино-мест/.test(u + ' ' + n)) return 'garage';
  if (/школ|детск|сад|поликлин|больниц|спорт|образован|гимназ|лицей|культур|музей|театр|библиот|пожар/.test(n)) return 'social';
  if (/нежил/.test(u)) return 'comm';
  return 'other'; };
if (typeof module !== 'undefined') module.exports = { clsLand, clsBuilding };
